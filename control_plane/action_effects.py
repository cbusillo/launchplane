ACTION_EFFECTS: Mapping[str, ActionEffect] = MappingProxyType(
    {action: declaration.effect for action, declaration in ACTION_DECLARATIONS.items()}
)


def action_requires_product_coverage(action: str) -> bool:
    declaration = ACTION_DECLARATIONS.get(action)
    return declaration is not None and declaration.service_scope == "products"


def action_effect(action: str) -> ActionEffect | None:
    return ACTION_EFFECTS.get(action)


def agent_read_role_covers(action: str) -> bool:
    return action_effect(action) in {"read", "plan"}
